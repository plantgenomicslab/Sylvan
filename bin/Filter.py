RF_RESCUE_THRESHOLD = 0.6  # Minimum RF Keep probability to rescue undecided genes

def semiSupRandomForest(data, predictors, busco_table, num_trees,
                        seed=None, recycle_prob=0.95, maxiter=5, repeat_cutoff=0.5):
	"""Iterative semi-supervised random forest for gene model classification.

	Starting from heuristic Keep/Discard seed labels, trains an RF and
	recycles high-confidence predictions (>= recycle_prob) into the training
	set.  Repeats until no new genes are recycled or maxiter is reached.

	Remaining undecided genes are rescued via two tiers:
	  1. RF Keep probability > RF_RESCUE_THRESHOLD (excluding TE-only genes)
	  2. Pfam domain present, not repeat-dominated, no RexDB hit

	Args:
		data:         DataFrame from filter_genes() with 'label' column
		predictors:   Number of features considered per RF split (max_features)
		busco_table:  Path to BUSCO full_table.tsv for monitoring
		num_trees:    Number of trees in the RF ensemble
		seed:         Random seed for reproducibility
		recycle_prob: Confidence threshold to recycle predictions into training
		maxiter:      Maximum number of re-training iterations

	Returns:
		(kept_df, process_dict): kept transcript IDs and training diagnostics
	"""
	# Load BUSCO table to monitor completeness during training
	busco = pd.read_csv(busco_table, sep="\t", comment="#", usecols=(0, 1, 2),
	                     names=["busco_id", "status", "transcript_id"])
	busco = busco.loc[busco["status"] != "Missing"].reset_index(drop=True)

	# Split into labeled (train) and unlabeled (test)
	train = data.loc[data["label"] != "None"].set_index("transcript_id")
	test = data.loc[data["label"] == "None"].set_index("transcript_id")
	feature_cols = [c for c in data.columns if c not in ("transcript_id", "label")]

	x_train = prepare_features(train, feature_cols)
	y_train = train.loc[:, train.columns == "label"]
	x_test = prepare_features(test, feature_cols)

	process = {"kept": [], "discarded": [], "kept_buscos": [], "discarded_buscos": [], "OOB": []}

	# Entry guards for degenerate label sets (issue #20.4). Without these,
	# maxiter=0 leaves `model`/`kept` undefined (NameError in the rescue block),
	# and an empty seed set makes sklearn's fit() raise on a 0-row matrix.
	maxiter = max(1, maxiter)
	if x_train.empty:
		print("WARNING: no heuristic seed labels; keeping all transcripts unfiltered.")
		return pd.DataFrame(data["transcript_id"].tolist(), columns=["transcript_id"]), process

	for iteration in range(maxiter):
		discarded = y_train[y_train["label"] == "Discard"].index
		kept = y_train[y_train["label"] == "Keep"].index

		process["discarded"].append(len(discarded))
		process["kept"].append(len(kept))

		# Count BUSCOs in kept/discarded sets
		kept_buscos = busco.loc[busco["transcript_id"].isin(kept), "busco_id"].unique()
		dis_buscos = busco.loc[busco["transcript_id"].isin(discarded), "busco_id"].unique()
		process["discarded_buscos"].append(len(dis_buscos))
		process["kept_buscos"].append(len(kept_buscos))

		# Train RF
		model = RandomForestClassifier(
			n_estimators=num_trees,
			max_features=predictors,
			random_state=seed,
			oob_score=True,
			n_jobs=-1,   # issue #20.12: parallelise RF over ~48k genes x maxiter
		)
		model.fit(x_train, y_train.to_numpy().reshape(-1,))
		process["OOB"].append(1 - model.oob_score_)

		# Nothing is unlabeled -- either the heuristic decided every gene, or the
		# previous iteration recycled the last of them. sklearn rejects a 0-row
		# matrix, so stop before predicting rather than raise.
		if x_test.empty:
			break

		# Predict unlabeled genes
		yhat = pd.DataFrame({
			"prediction": model.predict(x_test),
			"transcript_id": x_test.index,
		})
		yprob = pd.DataFrame(model.predict_proba(x_test), columns=model.classes_)
		yhat = pd.concat([yhat.reset_index(drop=True), yprob], axis=1)
		yhat["pred_prob"] = yhat.apply(lambda row: row[row["prediction"]], axis=1)

		# Recycle high-confidence predictions into training set
		confident = yhat[yhat["pred_prob"] > recycle_prob]
		if len(confident) == 0:
			break

		# Merge confident predictions back with full feature data
		recycle = confident[["transcript_id", "prediction"]].copy()
		recycle = recycle.merge(data, on="transcript_id", how="left")
		recycle["label"] = recycle["prediction"]
		recycle = recycle.set_index("transcript_id")

		recycle_features = prepare_features(recycle, feature_cols)
		x_train = pd.concat([x_train, recycle_features], axis=0)
		y_train = pd.concat([y_train, recycle.loc[:, recycle.columns == "label"]], axis=0)
		x_test = x_test[~x_test.index.isin(recycle.index)]

	else:
		# for-else: only runs if the loop was NOT broken out of (i.e., hit maxiter)
		print(f"Training stopped at a maximum of {maxiter} iterations.")

	# --- Rescue undecided genes ---
	if len(x_test) > 0:
		final_prob = pd.DataFrame(
			model.predict_proba(x_test), columns=model.classes_, index=x_test.index,
		)
		keep_prob = final_prob["Keep"] if "Keep" in final_prob.columns else pd.Series(0, index=x_test.index)

		# Tier 1: RF predicts Keep above rescue threshold
		rf_keep = keep_prob[keep_prob > RF_RESCUE_THRESHOLD].index.tolist()

		# Identify TE-only genes: RexDB hit without BLAST homology = transposon
		evidence = data.set_index("transcript_id").reindex(x_test.index)
		te_genes = set()
		if "rex_pident" in evidence.columns and "blast_pident" in evidence.columns:
			has_rex = evidence["rex_pident"].fillna(0) > 0
			no_blast = ~(evidence["blast_pident"].fillna(0) > 0)
			te_genes = set(evidence[has_rex & no_blast].index)
		rf_keep = [g for g in rf_keep if g not in te_genes]

		# Tier 2: Pfam domain present — keep unless repeat-dominated or TE-derived
		pfam_rescue = []
		if "PFAM" in evidence.columns and "REPEAT" in evidence.columns:
			has_pfam = evidence["PFAM"] == True
			not_repeat = evidence["REPEAT"].fillna(0) <= repeat_cutoff  # issue #20.6: honour --repcov
			no_rexdb = ~(evidence["rex_pident"].fillna(0) > 0) if "rex_pident" in evidence.columns else True
			pfam_rescue = evidence[has_pfam & not_repeat & no_rexdb].index.tolist()

		# Tier 3: BUSCO safety net — never discard a gene with a Complete BUSCO hit
		busco_complete = busco.loc[busco["status"].isin(["Complete", "Duplicated"]), "transcript_id"]
		busco_rescue = [g for g in x_test.index if g in busco_complete.values]

		# Combine all tiers (deduplicated)
		# Note: MINIPROT column is available as an RF feature but not used as
		# a rescue condition — miniprot coverage alone does not discriminate
		# between functional genes and pseudogenes in undecided sets.
		rescued = list(set(rf_keep + pfam_rescue + busco_rescue))
		undecided_disc = len(x_test) - len(rescued)
		kept = kept.tolist() + rescued
		print(f"Undecided None genes: {len(x_test)} "
		      f"(RF>{RF_RESCUE_THRESHOLD}: {len(rf_keep)}, "
		      f"Pfam rescue: {len(pfam_rescue)}, "
		      f"BUSCO rescue: {len(busco_rescue)}, "
		      f"TE excluded: {len(te_genes)}, "
		      f"total kept: {len(rescued)}, discarded: {undecided_disc})")

	# BUSCO safety net over the FULL result (issue #20.2): the in-loop Tier-3
	# rescue only reached undecided genes, so a Complete/Duplicated-BUSCO gene
	# that the heuristic *seeded* as Discard was never rescued — contradicting
	# "never discard a gene with a Complete BUSCO hit". Force them back in here.
	kept = list(kept)
	kept_set = set(kept)
	busco_complete_ids = set(
		busco.loc[busco["status"].isin(["Complete", "Duplicated"]), "transcript_id"]
	)
	present_ids = set(data["transcript_id"])
	forced = [g for g in busco_complete_ids if g in present_ids and g not in kept_set]
	if forced:
		print(f"BUSCO safety net: rescued {len(forced)} Complete/Duplicated-BUSCO "
		      f"genes that were seeded/predicted Discard.")
		kept.extend(forced)

	return pd.DataFrame(kept, columns=["transcript_id"]), process


def load_transcript_coords(gff_path):
	"""Map transcript_id -> (chrom, start, end) from a GFF3."""
	coords = {}
	with open(gff_path) as fh:
		for line in fh:
			if line.startswith("#"):
				continue
			cols = line.rstrip("\n").split("\t")
			if len(cols) < 9 or cols[2] not in ("mRNA", "transcript"):
				continue
			match = re.search(r"ID=([^;]+)", cols[8])
			if match:
				coords[match.group(1)] = (cols[0], int(cols[3]), int(cols[4]))
	return coords


def load_frameshift_intervals(miniprot_gff):
	"""Read protein-to-genome alignments carrying a frameshift.

	miniprot records ``Frameshift=N`` on its mRNA lines when the spliced
	alignment of a reference protein needs a frame correction at that locus --
	direct evidence of a disabled coding sequence.  Alignments with N == 0 are
	skipped.  ``StopCodon`` is deliberately NOT used: miniprot tags it on normal
	terminal stops too, so it overlaps ~95% of gene models and carries no signal.

	Returns {chrom: (starts_sorted, ends_sorted)} for O(log m) overlap counting.
	"""
	per_chrom = {}
	with open(miniprot_gff) as fh:
		for line in fh:
			if line.startswith("#"):
				continue
			cols = line.rstrip("\n").split("\t")
			if len(cols) < 9 or cols[2] != "mRNA":
				continue
			match = re.search(r"Frameshift=(\d+)", cols[8])
			if not match or int(match.group(1)) < 1:
				continue
			per_chrom.setdefault(cols[0], []).append((int(cols[3]), int(cols[4])))
	prepared = {}
	for chrom, spans in per_chrom.items():
		prepared[chrom] = (sorted(s for s, _ in spans), sorted(e for _, e in spans))
	return prepared


def count_frameshift_support(intervals, chrom, start, end):
	"""Number of frameshift alignments overlapping [start, end] on chrom.

	An interval [s, e] fails to overlap iff s > end or e < start, and those two
	sets are disjoint for well-formed intervals, so
	``overlaps = |{s <= end}| - |{e < start}|`` -- two binary searches instead of
	a scan.  With ~22k intervals and ~50k transcripts a linear scan per
	transcript would be ~10^9 comparisons.
	"""
	entry = intervals.get(chrom)
	if not entry:
		return 0
	starts, ends = entry
	return bisect.bisect_right(starts, end) - bisect.bisect_left(ends, start)


def load_subject_exon_counts(subject_gffs):
	"""Map reference-protein ID -> exon count of its transcript.

	Used to ask whether a single-exon model's best hit is multi-exon, i.e. whether
	the model looks like a retrocopy of a spliced parent.  Two namespaces resolve:

	  NCBI-style (Bra.gff3):  CDS carries protein_id=XP_...; its Parent is the
	                          rna-XM_... whose exons we count.
	  GWH-style (Rsa.gff3):   GWHPCBIT... appears on the CDS line directly.

	Subjects that resolve to nothing (e.g. AT* with no GFF3 among the neighbour
	inputs, or the target species' own annotation) are simply absent from the
	result and are treated as unknown by the caller -- never as evidence.
	"""
	exon_counts = {}
	prot_to_rna = {}
	for path in subject_gffs:
		if not path or not os.path.exists(path):
			continue
		with open(path) as fh:
			for line in fh:
				if line.startswith("#"):
					continue
				cols = line.rstrip("\n").split("\t")
				if len(cols) < 9:
					continue
				attrs = cols[8]
				if cols[2] == "exon":
					match = re.search(r"Parent=([^;,]+)", attrs)
					if match:
						exon_counts[match.group(1)] = exon_counts.get(match.group(1), 0) + 1
				elif cols[2] == "CDS":
					parent = re.search(r"Parent=([^;,]+)", attrs)
					if not parent:
						continue
					for pat in (r"protein_id=([^;]+)", r"(GWHPCBIT[0-9]+)"):
						pid = re.search(pat, attrs)
						if pid:
							prot_to_rna.setdefault(pid.group(1), parent.group(1))
							break
	return {prot: exon_counts.get(rna, 0) for prot, rna in prot_to_rna.items()}


# Pfam domains that mark a model as transposon-derived rather than functional.
# Listed explicitly rather than pattern-matched: substring rules misfire badly
# here -- "gag" catches GAGA_bind (a GAGA-binding transcription factor), "hAT"
# catches HATPase_c (histidine kinase ATPase), "rve" catches RVE6 (REVEILLE 6, a
# circadian MYB), "DDE" catches PDDEXK_6, and "RNase_H" catches the real RNase H2
# subunits.  All are genuine plant genes.
#
# Membership below was decided by measurement, not by the domain's name.  Every
# candidate was scored against two tracks that know nothing about Pfam --
# RepeatMasker/EDTA coverage and BLASTp vs RexDB transposon proteins -- plus
# expression.  Admission rule: (repeat >= 15% or RexDB >= 5%) and expressed <= 15%,
# against a Pfam-wide baseline of repeat 2.5%, RexDB 0.4%, expressed 51.5%.
# Domains whose carriers are mostly expressed real genes are in TE_PFAM_TIER2.
TE_PFAM_EXACT = frozenset({
	# original set, all re-verified on this run
	"zf-RVT", "MULE", "DBD_Tnp_Mut", "rve", "SH3_retrovirus", "Dimer_Tnp_hAT",
	"hAT-like_RNase-H", "hATC", "Integrase_H2C2", "Integrase_Zn",
	"gag_pre-integrs", "Transpos_assoc", "Retrotransp-rel", "Peptidase_A17",
	# retroelement internal proteins
	"RT_RNaseH", "RT_RNaseH_2", "RVP_2", "Asp_protease_2", "gag-asp_proteas",
	"Pol_BBD", "SH3_Tf2-1", "ATHILA", "Ty3_capsid",
	# Ty3/gypsy gag capsid (PEG10/RTL1 are domesticated in mammals, not plants)
	"PEG10_N-capsid", "PEG10-RTL1_C-capsid", "PRO_PEG10-RTL1", "DUF4219",
	# DNA transposases and their derived domains
	"Plant_tran", "DUF4371", "DUF659", "DUF4218", "TnsB_C", "Phage_integrase",
	"ZBED1_RNase-like", "ZBED1_RNase-like_helical", "zf-BED",
	# Helitron
	"DUF4216",
	# uncharacterised but measured TE-like (repeat 25-85%, expressed 0-6%)
	"DUF8418", "DUF8803", "DUF1633",
})
TE_PFAM_PREFIX = ("RVT_", "Transposase_", "DDE_Tnp_", "Retrotran_gag",
                  "Retrotrans_gag")

# Borderline: TE-derived in origin but with a real domesticated-gene population
# in plants, so withdrawing domain protection would kill genuine genes.  SWIM and
# PIF1 are the clearest cases -- FAR1/FHY3 are domesticated MuDR transposases,
# and Pfam PIF1 is the PIF1 helicase, unrelated to PIF/Harbinger transposases;
# both carry ~77% BLAST support.  Opt in with --te-pfam-tier2 to measure the cost.
TE_PFAM_TIER2 = frozenset({
	"SWIM", "PIF1", "Pif1_2B_dom", "zf-BED_2", "DUF1985", "zf-CCHC_4",
})


def _is_te_domain(name, tier2=False):
	if name in TE_PFAM_EXACT or name.startswith(TE_PFAM_PREFIX):
		return True
	return tier2 and name in TE_PFAM_TIER2


def load_pfam_domains(pfam_file):
	"""transcript_id -> set of Pfam domain names (hmm_name column)."""
	domains = {}
	if not os.path.exists(pfam_file):
		return domains
	with open(pfam_file) as fh:
		for line in fh:
			if line.startswith("#"):
				continue
			cols = line.split()
			if len(cols) < 8:
				continue
			domains.setdefault(cols[0], set()).add(cols[6])
	return domains


def transcripts_with_only_te_domains(pfam_file, tier2=False):
	"""transcript_ids whose every Pfam hit is a transposon domain.

	A model carrying RVT_1 and nothing else is a retroelement wearing a domain,
	and the ``~has_pfam`` guards in the discard paths would otherwise shield it --
	the domain evidence protects exactly the thing the filter is meant to remove.
	One non-TE domain is enough to keep the protection: a gene that has picked up
	a transposon insertion alongside a real domain is still a gene.
	"""
	te_only = set()
	for tid, names in load_pfam_domains(pfam_file).items():
		if names and all(_is_te_domain(n, tier2) for n in names):
			te_only.add(tid)
	return te_only


def load_cpc2_noncoding(cpc2_result):
	"""transcript_ids CPC2 calls noncoding.

	CPC2 scores Fickett TESTCODE, ORF length/integrity, and isoelectric point with
	a species-neutral SVM, so it is genuinely independent of lncDC's plant-trained
	model -- which is the point of consulting it.  Output is TSV with a header;
	the label column is ``coding_probability``'s neighbour, named ``label``.
	"""
	noncoding = set()
	if not cpc2_result or not os.path.exists(cpc2_result):
		return noncoding
	with open(cpc2_result) as fh:
		header = fh.readline().rstrip("\n").split("\t")
		try:
			id_i = header.index("#ID") if "#ID" in header else 0
			label_i = header.index("label")
		except ValueError:
			return noncoding
		for line in fh:
			cols = line.rstrip("\n").split("\t")
			if len(cols) <= label_i:
				continue
			if cols[label_i].strip().lower() == "noncoding":
				noncoding.add(cols[id_i].split()[0])
	return noncoding


def load_swissprot_hits(blast_file, pident_cutoff, qcovs_cutoff):
	"""transcript_ids with a SwissProt hit clearing both thresholds.

	SwissProt is manually curated, so a hit there is homology evidence that does
	not depend on another automated annotation being right.  That distinction
	matters for single-exon models: roughly half of the default protein DB is
	itself EVM-derived (R. sativus GWH sits at 18.2% single-exon, same as this
	assembly), so a dubious single-exon model can match an equally dubious
	single-exon model in another species and the two vouch for each other.
	"""
	hits = set()
	if not os.path.exists(blast_file):
		return hits
	with open(blast_file) as fh:
		for line in fh:
			cols = line.rstrip("\n").split("\t")
			if len(cols) < 13:
				continue
			try:
				pident, qcovs = float(cols[2]), float(cols[12])
			except ValueError:
				continue
			if pident > pident_cutoff * 100 and qcovs > qcovs_cutoff * 100:
				hits.add(cols[0])
	return hits


def load_best_hit_subjects(blast_file):
	"""transcript_id -> best-hit subject ID, by bitscore."""
	best = {}
	if not os.path.exists(blast_file):
		return {}
	with open(blast_file) as fh:
		for line in fh:
			cols = line.rstrip("\n").split("\t")
			if len(cols) < 12:
				continue
			try:
				bits = float(cols[11])
			except ValueError:
				continue
			if cols[0] not in best or bits > best[cols[0]][1]:
				best[cols[0]] = (cols[1], bits)
	return {q: v[0] for q, v in best.items()}


def load_busco_protected(busco_table):
	"""transcript_ids with a Complete/Duplicated BUSCO hit -- never discard these.

	Mirrors the safety net at :512 and :530 so the pseudogene pass cannot undo
	what the RF loop is explicitly forbidden from discarding.
	"""
	busco = pd.read_csv(busco_table, sep="\t", comment="#", usecols=(0, 1, 2),
	                    names=["busco_id", "status", "transcript_id"])
	protected = busco.loc[busco["status"].isin(["Complete", "Duplicated"]), "transcript_id"]
	return set(protected.dropna())


def apply_pseudogene_filter(keep, data, gff_path, busco_table, cov_cutoff=0.5,
                            tpm_cutoff=1.0, miniprot_gff=None, fs_min_support=2,
                            output_dir=None, subject_gffs=(), retro_min_subject_exons=2):
	"""Remove pseudogene candidates from an RF-accepted transcript set.

	Runs AFTER the random forest, deliberately: adding either rule as an RF
	feature or seed-label term changes the feature space and perturbs every tree
	(a fillna on ``singleExon`` alone moved the gene count by 961), which makes
	the effect of these rules impossible to attribute.  As a post-pass the delta
	is exactly the transcripts matched here.

	Rule A -- no functional evidence, homology only:
	    TPM == 0 AND no Pfam domain AND coverage < cov_cutoff AND has a BLAST hit.
	    Similarity to a parent gene while being transcriptionally silent and
	    domain-free is the classic pseudogene signature.  The BLAST requirement
	    matters: without it the same profile describes a failed prediction, which
	    is a different problem.

	Rule B -- frameshifted locus:
	    >= fs_min_support miniprot alignments with Frameshift>0 overlap the
	    transcript AND TPM < tpm_cutoff AND no Pfam domain.  Requiring multiple
	    independent alignments guards against a single mis-mapped paralog; one
	    alignment overlaps ~27% of all models and is not evidence.

	Rule C -- retrocopy (intron loss):
	    the model is single-exon AND its BLAST best hit is a multi-exon transcript
	    (>= retro_min_subject_exons exons) AND TPM < tpm_cutoff AND no Pfam domain.
	    A processed pseudogene is single-exon because it entered as reverse-
	    transcribed mRNA while its parent stayed spliced.  Subjects whose exon
	    count cannot be resolved (no GFF3 for that namespace) are treated as
	    unknown and never trigger the rule.

	Args:
		keep:  DataFrame with a transcript_id column (RF output)
		data:  evidence table indexed-by-column transcript_id
		gff_path, busco_table: source GFF3 and BUSCO full_table.tsv
		cov_cutoff, tpm_cutoff, fs_min_support: rule thresholds
		miniprot_gff: miniprot GFF3; when None, Rule B is skipped
		output_dir: directory holding BLASTP.OUT.TMP; needed for Rule C
		subject_gffs: GFF3s resolving best-hit subjects to exon counts;
		    empty disables Rule C
		retro_min_subject_exons: subject exon count that counts as spliced

	Returns:
		(kept DataFrame, {transcript_id: reason}, stats dict)
	"""
	evidence = data.set_index("transcript_id")
	protected = load_busco_protected(busco_table)
	kept_ids = [t for t in keep["transcript_id"] if t in evidence.index]
	subset = evidence.loc[kept_ids]

	no_pfam = subset["PFAM"].isna()
	has_blast = subset["blast_pident"].notna()
	tpm = pd.to_numeric(subset["TPM"], errors="coerce").fillna(0)
	cov = pd.to_numeric(subset["COVERAGE"], errors="coerce").fillna(0)

	rule_a = (tpm == 0) & no_pfam & (cov < cov_cutoff) & has_blast

	rule_b = pd.Series(False, index=subset.index)
	fs_counts = {}
	if miniprot_gff:
		intervals = load_frameshift_intervals(miniprot_gff)
		coords = load_transcript_coords(gff_path)
		for tid in subset.index:
			pos = coords.get(tid)
			fs_counts[tid] = count_frameshift_support(intervals, *pos) if pos else 0
		fs_series = pd.Series(fs_counts).reindex(subset.index).fillna(0)
		rule_b = (fs_series >= fs_min_support) & (tpm < tpm_cutoff) & no_pfam

	rule_c = pd.Series(False, index=subset.index)
	subj_resolved = 0
	if subject_gffs and output_dir:
		subj_exons = load_subject_exon_counts(subject_gffs)
		best_subj = load_best_hit_subjects(os.path.join(output_dir, "BLASTP.OUT.TMP"))
		# singleExon is True / NaN in `data`; NaN means multi-exon. Resolve it into
		# a local boolean -- do NOT write it back, since the NaN pattern feeds the
		# {col}_missing indicator in prepare_features (see issue #25).
		is_single = subset["singleExon"].notna() & (subset["singleExon"] == True)
		subj_multi = []
		for tid in subset.index:
			sid = best_subj.get(tid)
			n = subj_exons.get(sid) if sid else None
			if n is not None:
				subj_resolved += 1
			subj_multi.append(bool(n and n >= retro_min_subject_exons))
		subj_multi = pd.Series(subj_multi, index=subset.index)
		rule_c = is_single & subj_multi & (tpm < tpm_cutoff) & no_pfam

	# Priority: frameshift (direct disabling evidence) > retrocopy (structural)
	# > absent expression. Most specific claim wins the label.
	reasons = {}
	for tid in subset.index[rule_b]:
		reasons[tid] = "pseudogene_frameshift"
	for tid in subset.index[rule_c]:
		reasons.setdefault(tid, "pseudogene_retrocopy")
	for tid in subset.index[rule_a]:
		reasons.setdefault(tid, "pseudogene_no_evidence")

	rescued = {t for t in reasons if t in protected}
	for tid in rescued:
		del reasons[tid]

	stats = {
		"rule_A_no_evidence": int(rule_a.sum()),
		"rule_B_frameshift": int(rule_b.sum()),
		"rule_C_retrocopy": int(rule_c.sum()),
		"overlap_A_B": int((rule_a & rule_b).sum()),
		"overlap_A_C": int((rule_a & rule_c).sum()),
		"overlap_B_C": int((rule_b & rule_c).sum()),
		"subjects_resolved": subj_resolved,
		"BUSCO_rescued": len(rescued),
		"removed_total": len(reasons),
	}
	remaining = keep.loc[~keep["transcript_id"].isin(reasons)].copy()
	return remaining, reasons, stats


def _classify_discard(df):
	"""Classify discarded genes into three categories based on evidence.

	Categories (applied in priority order):
	  TE_related:  RexDB hit (transposon-derived or TE-invaded gene)
	  lncRNA:      Predicted as lncRNA by lncDC classifier
	  pseudogene:  Everything else (low/no evidence, non-functional)

	Args:
		df: DataFrame indexed by transcript_id with evidence columns

	Returns:
		Series of discard reason strings
	"""
	reasons = pd.Series("pseudogene", index=df.index)

	has_rex = df["rex_pident"].fillna(0) > 0 if "rex_pident" in df.columns else pd.Series(False, index=df.index)
	is_lncrna = df["LncRNA_predict"].fillna(0) > 0.5 if "LncRNA_predict" in df.columns else pd.Series(False, index=df.index)

	# Priority: TE_related > lncRNA > pseudogene
	reasons[has_rex] = "TE_related"
	reasons[~has_rex & is_lncrna] = "lncRNA"

	return reasons


